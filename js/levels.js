  /* 沒有指定名字的棋子用預設名稱（見 engine.defaultLabels）。 */
  function autoLabels(grid) {
    const letters = [];
    grid.join('').split('').forEach((ch) => { if (ch !== '.' && !letters.includes(ch)) letters.push(ch); });
    const names = E.defaultLabels(E.fromGrid(grid));
    const labels = {};
    letters.forEach((ch, i) => { labels[ch] = names[i]; });
    return labels;
  }

  const ORDER = CATEGORIES.map((c) => c.id);
  RAW.sort((a, b) => ORDER.indexOf(a.category) - ORDER.indexOf(b.category) || a.minMoves - b.minMoves);

  const LEVELS = RAW.map((r) => {
    const labels = Object.assign(autoLabels(r.grid), r.labels || {});
    const st = E.fromGrid(r.grid, labels, r.exit);
    return {
      id: r.id,
      name: r.name,
      category: r.category,
      difficulty: E.difficultyFor(r.minMoves),
      description: r.description,
      board: { cols: st.cols, rows: st.rows },
      exit: { side: st.exit.side, at: st.exit.at },
      goal: { x: st.goal.x, y: st.goal.y },
      pieces: E.stateToPieces(st),
      minMoves: r.minMoves,
      solvable: true,
      source: 'builtin',
    };
  });

  const api = { CATEGORIES, LEVELS };
